"""Generate the Sphinx examples gallery from the packaged Python scripts.

The files in src/ase2sprkkr/examples are the source of truth. This
tool reads module docstrings, links to the sources and API documentation,
and emits literalinclude directives to display actual source code.
No ASE or SPR-KKR installation is required to generate the gallery.
"""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "ase2sprkkr" / "examples"
OUTPUT = Path(__file__).with_name("examples_generated.inc")
EXAMPLE_NAME = re.compile(r"A([0-9]{2})_.+")


def render_gallery(source: Path = SOURCE) -> str:
    """Render an RST fragment indexed from the current example scripts."""
    lines = [
        ".. Automatically generated by doc_src/examples.py.",
        ".. Edit the Python examples, not this file.",
        "",
    ]
    count = 0
    tick = chr(96)
    for directory in sorted(source.iterdir()):
        if not directory.is_dir():
            continue
        match = EXAMPLE_NAME.fullmatch(directory.name)
        if match is None:
            continue

        scripts = sorted(
            script for script in directory.glob("*.py")
            if not script.name.startswith("_")
        )
        for script in scripts:
            # Reading the AST avoids importing optional scientific packages.
            tree = ast.parse(script.read_text(encoding="utf-8"), filename=str(script))
            docstring = ast.get_docstring(tree) or "No description provided."
            description = " ".join(docstring.split("\n\n", 1)[0].split())
            heading = (
                directory.name if len(scripts) == 1
                else f"{directory.name}: {script.name}"
            )
            module = f"ase2sprkkr.examples.{directory.name}.{script.stem}"
            relative_source = f"../src/ase2sprkkr/examples/{directory.name}/{script.name}"
            number = int(match.group(1))
            lines.extend([
                heading,
                "~" * len(heading),
                "",
                description,
                "",
                f"* :py:mod:{tick}Module documentation <{module}>{tick}",
                f"* :download:{tick}Download {script.name} <{relative_source}>{tick}",
                f"* Copy the example: {tick * 2}ase2sprkkr example {number} --copy ./my-example{tick * 2}",
                "",
                f".. literalinclude:: {relative_source}",
                "   :language: python",
                "   :linenos:",
                f"   :caption: {script.name}",
                "",
            ])
            count += 1
    if count == 0:
        raise RuntimeError(f"No example scripts found in {source}")
    return "\n".join(lines) + "\n"


def generate_gallery(
    source: Path = SOURCE, output: Path = OUTPUT, *, check: bool = False
) -> None:
    """Generate a gallery file or check it against the current source tree."""
    rendered = render_gallery(source)
    existing = output.read_text(encoding="utf-8") if output.exists() else None
    if check:
        if existing != rendered:
            raise RuntimeError(
                f"{output} is missing or outdated; run python doc_src/examples.py"
            )
        return
    if existing != rendered:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the gallery is up-to-date")
    args = parser.parse_args()
    generate_gallery(check=args.check)
